""" USO DE PRINT


"""
# podemos imprimir valores numericos 
print(1234)
print(2.71828)

# podemos imprimir cadenas de texto mediante la comilla doble o simple
print("Esta es una cadena")
print('Esta es una cadena')

# Podemos unir cadenas meidante el uso de la coma
print("Esta", "es", "una", "cadena")

# Podemos unir cadenas con otros tipos de datos
print("Hola", "hoy", "es", 17, "de", "agosto", "del", 2026)

# Podemos unir cadenas mediente el operador de suma
# a diferencia del uso de la coma cuando concatenamos cadenas con el operador
# de sume (+) se requiere insertar espacios entre las palabras
print("Hola" + "como" + "estan")
print("Hola" + " como " + "estan")

# sin embargo cuando concatemos cadenas con el signo + no podemos mezclar
# distintos tipos de datos
# print("Agosto" + 2026)

# Podemos imprimir operaciones
print('La suma de 10 + 30 es ',10 + 30)
print('El valor 10 elevado al cuadraro es ', 10 ** 2)
