""" VARIABLES 

    En Python, todo es un objeto y los tipos de datos definen la naturaleza de 
    la información que esos objetos contienen (números, texto, listas, etc.)
    Las variables no son más que etiquetas o 'nombres' que apuntan a esos 
    objetos en la memoria. Cuando asignas un valor a una variable (por ejemplo, 
    edad = 25), la variable edad simplemente hace referencia al objeto 25, el 
    cual es de tipo entero (int).
    
    Tipos de datos primarios (o fundamentales) más utilizados en Python 
    organizados por su categoría:
"""

# 1. Tipos numéricos
# int (Enteros): Números sin parte decimal, ya sean positivos o negativos.
cantidad = 100
temperatura = -5

# float (Decimales / Coma flotante): Números que contienen un punto decimal.
precio = 19.99
pi = 3.14159

# bool (Booleanos): Representan valores de verdad lógica: solo pueden ser 
# True (Verdadero) o False (Falso). (Técnicamente en Python los booleanos son 
# una subclase de los enteros, donde True vale 1 y False vale 0).
es_mayor_de_edad = True
descuento_aplicado = False

# 2. Tipo Texto / Cadena de Caracteres
# str (Cadenas / Strings): Secuencias de texto delimitadas por comillas 
# simples ('...') o dobles ("...").
nombre = "Javier"
mensaje = 'Hola mundo'
